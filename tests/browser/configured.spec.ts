import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const base = process.env.CONFIGURED_TEST_URL;
test.skip(!base, 'Requires the explicitly launched local Supabase mock and configured QA server.');
test('published detail, fullscreen keyboard gallery, enquiry and requested viewing', async ({ page, request }, info) => {
  const suffix = String(Date.now()).slice(-8);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(`${base}/properties/qa-residence`);
  await expect(page.getByRole('heading', { name: 'QA Residence — Test Only', exact: true })).toBeVisible();
  await expect(page.getByText('500 m²', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Explore gallery' }).click(); await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('dialog').getByText(/02 \/ 02/)).toBeVisible(); await page.keyboard.press('ArrowLeft');
  await expect(page.getByRole('dialog').getByText(/01 \/ 02/)).toBeVisible(); await page.keyboard.press('Escape');
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze(); expect(axe.violations).toEqual([]);
  await page.getByLabel('YOUR NAME', { exact: true }).fill('QA Viewing Buyer');
  await page.getByLabel('PHONE NUMBER', { exact: true }).fill(`+233 000 ${suffix}1`);
  await page.getByLabel('PREFERRED DATE', { exact: true }).fill('2099-01-15'); await page.getByLabel('PREFERRED TIME (GHANA)', { exact: true }).fill('09:30');
  await page.getByRole('button', { name: 'Send viewing request' }).click();
  await expect(page.getByRole('status')).toContainText('not confirmed');
  await page.getByRole('button', { name: 'Make an enquiry', exact: true }).click();
  await page.getByLabel('YOUR NAME', { exact: true }).fill('QA Storage Failure');
  await page.getByLabel('PHONE NUMBER', { exact: true }).fill(`+233 000 ${suffix}2`);
  await page.getByRole('button', { name: 'Send enquiry', exact: true }).click();
  await expect(page.locator('#viewing').getByRole('alert')).toContainText('could not be saved');
  await page.getByLabel('YOUR NAME', { exact: true }).fill('QA Enquiry Buyer');
  await page.getByRole('button', { name: 'Send enquiry', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Your enquiry has been received');
  const draft = await request.get(`${base}/properties/qa-private-draft`); expect(draft.status()).toBe(404);
  const rejected = await request.post(`${base}/api/enquiries`, { data: { propertyId: '22222222-2222-4222-8222-222222222222', name: 'QA Draft', phone: `+233 000 ${suffix}3` } }); expect(rejected.status()).toBe(404);
  const log = await request.get('http://127.0.0.1:3002/_qa/requests'); const data = await log.json();
  expect(data.requests.some((r: { kind: string; status: string }) => r.kind === 'appointments' && r.status === 'requested')).toBe(true);
  expect(data.requests.some((r: { kind: string; status: string }) => r.kind === 'enquiries' && r.status === 'new')).toBe(true);
  expect(data.queries.every((q: { status: string }) => q.status === 'eq.published')).toBe(true);
  await page.screenshot({ path: `docs/qa/configured-detail-${info.project.name}.png`, fullPage: true });
});
