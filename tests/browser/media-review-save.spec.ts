import {test,expect} from '@playwright/test';
const base=process.env.MEDIA_REVIEW_TEST_URL,mock='http://127.0.0.1:3004';
const property='44444444-4444-4444-a444-444444444444',editor=`/admin/properties/${property}`;
test.skip(!base,'Opt-in loopback-only synthetic media-review backend.');
test.beforeEach(async({context,request})=>{
  expect(new URL(base!).hostname).toBe('127.0.0.1');
  await request.post(mock+'/_qa/reset');
  await context.addCookies([{name:'sp_admin_token',value:'local-synthetic-token',url:base!,httpOnly:true,sameSite:'Lax'}]);
});
test('a changed gallery keeps the explanation and requires fresh review before saving',async({page,request},info)=>{
  await page.goto(base+editor);
  const form=page.locator('.media-decision'),proof='Synthetic local review evidence, never an actual property confirmation.';
  const signature=await form.locator('[name=gallerySignature]').inputValue();
  await form.locator('[name=evidence]').fill(proof);await form.getByRole('checkbox').check();
  await request.post(mock+'/_qa/change');
  await form.getByRole('button',{name:'Save media identity confirmation',exact:true}).click();
  await expect(form.getByRole('alert')).toContainText('gallery changed');
  await expect(page).toHaveURL(base+editor);
  await expect(form.locator('[name=evidence]')).toHaveValue(proof);
  await expect(form.getByRole('checkbox')).not.toBeChecked();
  await expect(form.getByRole('button',{name:'Save media identity confirmation',exact:true})).toBeDisabled();
  expect((await(await request.get(mock+'/_qa/state')).json()).decision).toBeNull();
  await form.screenshot({path:info.outputPath('stale-review-preserved.png')});
  await form.getByRole('button',{name:'Reload gallery for review',exact:true}).click();
  await expect(form.locator('[name=gallerySignature]')).not.toHaveValue(signature);
  await expect(form.locator('[name=evidence]')).toHaveValue(proof);
  await expect(form.getByRole('checkbox')).not.toBeChecked();
  await expect(page.locator('.admin-media-list')).toContainText('Synthetic gallery version 1');
  await form.getByRole('checkbox').check();
  await form.getByRole('button',{name:'Save media identity confirmation',exact:true}).click();
  await expect(form.getByRole('status')).toContainText('Media identity confirmation saved');
  await expect(form.getByRole('heading')).toHaveText('Media identity confirmed');
  const state=await(await request.get(mock+'/_qa/state')).json();
  expect(state.decision.evidence).toBe(proof);expect(state.audits).toHaveLength(1);expect(state.propertyStatus).toBe('draft');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
test('native forms show a readable stale-gallery page and a fresh form can save',async({browser,request})=>{
  const context=await browser.newContext({javaScriptEnabled:false});
  await context.addCookies([{name:'sp_admin_token',value:'local-synthetic-token',url:base!,httpOnly:true,sameSite:'Lax'}]);
  const page=await context.newPage();await page.goto(base+editor);
  let form=page.locator('.media-decision');
  await form.locator('[name=evidence]').fill('Synthetic native-form evidence only, not actual inventory.');await form.getByRole('checkbox').check();
  await request.post(mock+'/_qa/change');
  await form.getByRole('button',{name:'Save media identity confirmation',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Media confirmation was not saved.'})).toBeVisible();
  await expect(page.getByText('The gallery changed',{exact:false})).toBeVisible();
  expect((await(await request.get(mock+'/_qa/state')).json()).decision).toBeNull();
  await page.getByRole('link',{name:'Reopen the property editor'}).click();
  form=page.locator('.media-decision');
  await form.locator('[name=evidence]').fill('Synthetic native-form evidence only, not actual inventory.');await form.getByRole('checkbox').check();
  await form.getByRole('button',{name:'Save media identity confirmation',exact:true}).click();
  await expect(form.getByRole('heading')).toHaveText('Media identity confirmed');
  expect((await(await request.get(mock+'/_qa/state')).json()).audits).toHaveLength(1);
  await context.close();
});
